import { describe, expect, it } from 'vitest'
import { accountBalance, allocatedToGoals, balanceSeries, lastMonths, monthlySeries, netWorth, reconcile, summarize, totalBalance, totalsByCategory } from './ledger'
import { monthRange } from './dates'
import { CASH, ENTERTAINMENT, FOOD, SALARY, setup, TRANSPORT } from '@/test/helpers'

const JUNE = monthRange('2025-06')

describe('reglas 1-2: ingresos y gastos mueven el saldo de la cuenta', () => {
  it('ingreso suma y gasto resta', async () => {
    const t = setup()
    await t.income(3_000_000, '2025-06-01')
    await t.expense(120_000, '2025-06-02')
    const d = await t.load()
    expect(accountBalance(d, CASH)).toBe(2_880_000)
    expect(totalBalance(d)).toBe(2_880_000)
  })
  it('respeta el saldo inicial', async () => {
    const t = setup()
    const id = await t.bank(500_000)
    await t.s.transactions.create({ type: 'expense', amount: 100_000, date: '2025-06-01', accountId: id, categoryId: FOOD })
    const d = await t.load()
    expect(accountBalance(d, id)).toBe(400_000)
    expect(accountBalance(d, CASH)).toBe(0)
  })
  it('permite saldos negativos', async () => {
    const t = setup()
    await t.expense(50_000, '2025-06-01')
    expect(accountBalance(await t.load(), CASH)).toBe(-50_000)
  })
})

describe('regla 3 y 10: transferencias', () => {
  it('mueven dinero entre cuentas sin alterar el patrimonio ni los ingresos/gastos', async () => {
    const t = setup()
    const bank = await t.bank(0)
    await t.income(1_000_000, '2025-06-01')
    const before = await t.load()
    await t.s.transfers.create({ fromAccountId: CASH, toAccountId: bank, amount: 400_000, date: '2025-06-03' })
    const d = await t.load()
    expect(accountBalance(d, CASH)).toBe(600_000)
    expect(accountBalance(d, bank)).toBe(400_000)
    expect(totalBalance(d)).toBe(totalBalance(before))
    const s = summarize(d.transactions, JUNE)
    expect(s.income).toBe(1_000_000)
    expect(s.expense).toBe(0)
    expect(s.net).toBe(1_000_000)
    expect(reconcile(d).ok).toBe(true)
  })
  it('rechaza origen igual a destino, montos inválidos y fechas futuras', async () => {
    const t = setup()
    const bank = await t.bank(0)
    await expect(t.s.transfers.create({ fromAccountId: CASH, toAccountId: CASH, amount: 10, date: '2025-06-01' })).rejects.toThrow(/distintos/)
    await expect(t.s.transfers.create({ fromAccountId: CASH, toAccountId: bank, amount: 0, date: '2025-06-01' })).rejects.toThrow()
    await expect(t.s.transfers.create({ fromAccountId: CASH, toAccountId: bank, amount: 10, date: '2025-06-16' })).rejects.toThrow(/futura/)
  })
  it('editar y eliminar una transferencia actualiza ambos saldos', async () => {
    const t = setup()
    const bank = await t.bank(0)
    const wallet = await t.bank(0, 'Nequi')
    const id = await t.s.transfers.create({ fromAccountId: CASH, toAccountId: bank, amount: 100_000, date: '2025-06-01' })
    await t.s.transfers.update(id, { fromAccountId: CASH, toAccountId: wallet, amount: 150_000, date: '2025-06-01' })
    let d = await t.load()
    expect(accountBalance(d, bank)).toBe(0)
    expect(accountBalance(d, wallet)).toBe(150_000)
    expect(accountBalance(d, CASH)).toBe(-150_000)
    await t.s.transfers.remove(id)
    d = await t.load()
    expect([accountBalance(d, bank), accountBalance(d, wallet), accountBalance(d, CASH)]).toEqual([0, 0, 0])
    await t.s.transfers.restore(id)
    expect(accountBalance(await t.load(), wallet)).toBe(150_000)
  })
})

describe('reglas 4-5: editar y eliminar mantienen los balances consistentes', () => {
  it('editar monto, cuenta y fecha recalcula todo', async () => {
    const t = setup()
    const bank = await t.bank(1_000_000)
    const id = await t.expense(200_000, '2025-05-20')
    await t.s.transactions.update(id, { type: 'expense', amount: 250_000, date: '2025-06-10', accountId: bank, categoryId: TRANSPORT, description: 'editado' })
    const d = await t.load()
    expect(accountBalance(d, CASH)).toBe(0)
    expect(accountBalance(d, bank)).toBe(750_000)
    expect(summarize(d.transactions, monthRange('2025-05')).expense).toBe(0)
    expect(summarize(d.transactions, JUNE).expense).toBe(250_000)
    expect(totalsByCategory(d.transactions, JUNE, 'expense')[0]?.categoryId).toBe(TRANSPORT)
    expect(reconcile(d).ok).toBe(true)
  })
  it('cambiar un gasto a ingreso exige una categoría de ingreso', async () => {
    const t = setup()
    const id = await t.expense(100, '2025-06-01')
    await expect(t.s.transactions.update(id, { type: 'income', amount: 100, date: '2025-06-01', accountId: CASH, categoryId: FOOD })).rejects.toThrow(/categoría/)
    await t.s.transactions.update(id, { type: 'income', amount: 100, date: '2025-06-01', accountId: CASH, categoryId: SALARY })
    expect(accountBalance(await t.load(), CASH)).toBe(100)
  })
  it('eliminar revierte el saldo y se puede deshacer', async () => {
    const t = setup()
    await t.income(1_000, '2025-06-01')
    const id = await t.expense(400, '2025-06-02')
    await t.s.transactions.remove(id)
    expect(accountBalance(await t.load(), CASH)).toBe(1_000)
    await expect(t.s.transactions.remove(id)).rejects.toThrow()
    await t.s.transactions.restore(id)
    expect(accountBalance(await t.load(), CASH)).toBe(600)
  })
  it('eliminar ingresos puede dejar saldo negativo pero consistente', async () => {
    const t = setup()
    const inc = await t.income(1_000, '2025-06-01')
    await t.expense(400, '2025-06-02')
    await t.s.transactions.remove(inc)
    const d = await t.load()
    expect(accountBalance(d, CASH)).toBe(-400)
    expect(reconcile(d).ok).toBe(true)
  })
})

describe('regla 6: las metas no son gastos', () => {
  it('aportar a una meta no cambia saldos, ingresos ni gastos', async () => {
    const t = setup()
    await t.income(2_000_000, '2025-06-01')
    await t.expense(500_000, '2025-06-02')
    const goal = await t.s.goals.create({ name: 'Computador', targetAmount: 5_000_000 })
    const before = await t.load()
    await t.s.goals.contribute({ goalId: goal, kind: 'deposit', amount: 700_000, date: '2025-06-05' })
    const d = await t.load()
    expect(totalBalance(d)).toBe(totalBalance(before))
    expect(summarize(d.transactions, JUNE)).toEqual(summarize(before.transactions, JUNE))
    expect(allocatedToGoals(d)).toBe(700_000)
    expect(allocatedToGoals(d, JUNE)).toBe(700_000)
  })
})

describe('agregados y regla 11: conciliación', () => {
  it('sin movimientos todo es cero y no hay porcentaje de ahorro', async () => {
    const t = setup()
    const d = await t.load()
    expect(summarize(d.transactions, JUNE)).toEqual({ income: 0, expense: 0, net: 0, savingsRate: null, txCount: 0 })
    expect(totalsByCategory(d.transactions, JUNE, 'expense')).toEqual([])
    expect(totalBalance(d)).toBe(0)
  })
  it('mes sin ingresos y gastos superiores a los ingresos', async () => {
    const t = setup()
    await t.expense(80_000, '2025-06-03')
    let s = summarize((await t.load()).transactions, JUNE)
    expect(s).toMatchObject({ income: 0, expense: 80_000, net: -80_000, savingsRate: null })
    await t.income(50_000, '2025-06-04')
    s = summarize((await t.load()).transactions, JUNE)
    expect(s.net).toBe(-30_000)
    expect(s.savingsRate).toBeCloseTo(-0.6)
  })
  it('categorías, serie mensual y balance concilian con los movimientos', async () => {
    const t = setup()
    await t.income(3_000_000, '2025-04-05')
    await t.expense(1_000_000, '2025-04-10')
    await t.income(3_200_000, '2025-05-05')
    await t.expense(1_100_000, '2025-05-12')
    await t.s.transactions.create({ type: 'expense', amount: 300_000, date: '2025-06-02', accountId: CASH, categoryId: ENTERTAINMENT })
    await t.expense(700_000, '2025-06-03')
    const d = await t.load()
    const months = lastMonths('2025-06', 3)
    expect(months).toEqual(['2025-04', '2025-05', '2025-06'])
    const series = monthlySeries(d.transactions, months)
    expect(series.map((p) => p.net)).toEqual([2_000_000, 2_100_000, -1_000_000])
    const total = summarize(d.transactions, { from: '2025-04-01', to: '2025-06-30' })
    expect(series.reduce((s, p) => s + p.income, 0)).toBe(total.income)
    expect(series.reduce((s, p) => s + p.expense, 0)).toBe(total.expense)
    const cats = totalsByCategory(d.transactions, JUNE, 'expense')
    expect(cats.reduce((s, c) => s + c.amount, 0)).toBe(summarize(d.transactions, JUNE).expense)
    expect(cats.reduce((s, c) => s + c.share, 0)).toBeCloseTo(1)
    expect(netWorth(d)).toBe(total.net)
    const bs = balanceSeries(d, ['2025-04-30', '2025-05-31', '2025-06-30'])
    expect(bs.map((b) => b.balance)).toEqual([2_000_000, 4_100_000, 3_100_000])
  })
  it('montos muy elevados mantienen exactitud', async () => {
    const t = setup()
    await t.income(9_000_000_000_000, '2025-06-01')
    await t.income(9_000_000_000_000, '2025-06-02')
    await t.expense(1, '2025-06-03')
    const d = await t.load()
    expect(totalBalance(d)).toBe(18_000_000_000_000 - 1)
    await expect(t.income(9_000_000_000_001, '2025-06-04')).rejects.toThrow()
  })
  it('saldo a una fecha pasada', async () => {
    const t = setup()
    await t.income(1_000, '2025-06-01')
    await t.expense(300, '2025-06-10')
    const d = await t.load()
    expect(accountBalance(d, CASH, '2025-06-05')).toBe(1_000)
    expect(accountBalance(d, CASH, '2025-06-10')).toBe(700)
  })
})
